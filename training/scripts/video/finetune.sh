#!/bin/bash

deepspeed --include="localhost:0,1,2,3" "$PROJECT_ROOT/llava/train/train_finetune.py" \
  --deepspeed "$PROJECT_ROOT/scripts/zero3.json" \
  --model_name_or_path "$MODEL_NAME_OR_PATH" \
  --version v1 \
  --data_path "$DATA_ROOT/data/processed_data/merged_train_finetune.jsonl" \
  --eval_data_path "$DATA_ROOT/data/processed_data/merged_val_finetune.jsonl" \
  --image_folder "$DATA_ROOT" \
  --vision_tower "$VISION_TOWER" \
  --pretrain_mm_mlp_adapter "$PRETRAIN_MM_MLP_ADAPTER" \
  --mm_projector_type mlp2x_gelu \
  --mm_vision_select_layer -2 \
  --mm_use_im_start_end False \
  --mm_use_im_patch_token False \
  --image_aspect_ratio pad \
  --group_by_modality_length False \
  --bf16 True \
  --output_dir "$OUTPUT_ROOT/vmcd_ispy/llava1.5-13b-24f-4part" \
  --num_train_epochs 5 \
  --per_device_train_batch_size 1 \
  --per_device_eval_batch_size 1 \
  --gradient_accumulation_steps 4 \
  --evaluation_strategy 'epoch' \
  --save_strategy "epoch" \
  --save_total_limit 2 \
  --learning_rate 2e-6 \
  --weight_decay 0. \
  --warmup_ratio 0.03 \
  --lr_scheduler_type "cosine" \
  --logging_steps 1 \
  --tf32 True \
  --model_max_length 2048 \
  --gradient_checkpointing True \
  --dataloader_num_workers 1 \
  --lazy_preprocess True \
  --load_best_model_at_end True \
  --metric_for_best_model "loss" \
  --prediction_loss_only True \
  --eval_accumulation_steps 2 \
  --run_name 'finetune' \
  --resume_from_checkpoint "$RESUME_FROM_CHECKPOINT" \
  2>&1 | tee "$OUTPUT_ROOT/training_log_13b.txt"
